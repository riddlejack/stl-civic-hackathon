"""N2 step 7: emit the closure classifier as plain SQL (DuckDB dialect) and check it agrees with classes.py.

Output: build/N2/closure_class.sql, which creates
  closure_text_class(text_norm, class, rule)            -- one row per known closing text
  closure_type_override(problemcode, text_norm, class, rule)
  macro closure_class(problemcode, publicresolution)    -- returns the class
  macro closure_rule(problemcode, publicresolution)     -- returns the rule id
Normalisation in SQL: lower(trim(regexp_replace(text, '\\s+', ' ', 'g'))).
Run: .venv/bin/python -I scripts/night/N2/08_sql_classifier.py
"""
import pathlib, sys
import duckdb

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from classes import TEXT_RULES, TYPE_OVERRIDES, PREFIX_RULES, classify  # noqa: E402

ROOT = HERE.parents[2]
B = ROOT / "build" / "N2"
q = lambda s: "'" + s.replace("'", "''") + "'"
NORM = "lower(trim(regexp_replace(coalesce({x}, ''), '\\s+', ' ', 'g')))"
lines = ["-- St. Louis 311 closure classes (N2, 13-14 Oct 2026). Generated by scripts/night/N2/08_sql_classifier.py.",
         "-- Classes: done, handed_off, converted, no_action, info_other, blank. Rule table drafted by an AI model; review it.",
         "CREATE OR REPLACE TABLE closure_text_class (text_norm VARCHAR PRIMARY KEY, class VARCHAR, rule VARCHAR);",
         "INSERT INTO closure_text_class VALUES"]
lines.append(",\n".join(f"  ({q(t)}, {q(c)}, {q(r)})" for t, (c, r) in sorted(TEXT_RULES.items())) + ";")
lines.append("CREATE OR REPLACE TABLE closure_type_override (problemcode VARCHAR, text_norm VARCHAR, class VARCHAR, rule VARCHAR);")
lines.append("INSERT INTO closure_type_override VALUES")
lines.append(",\n".join(f"  ({q(pc)}, {q(t)}, {q(c)}, {q(r)})" for (pc, t), (c, r) in TYPE_OVERRIDES.items()) + ";")
pref = " ".join(f"WHEN starts_with({NORM.format(x='t')}, {q(p)}) THEN {q(v[0])}" for p, v in PREFIX_RULES)
prefr = " ".join(f"WHEN starts_with({NORM.format(x='t')}, {q(p)}) THEN {q(v[1])}" for p, v in PREFIX_RULES)
lines.append(f"""CREATE OR REPLACE MACRO closure_class(pc, t) AS CASE
  WHEN {NORM.format(x='t')} = '' THEN 'blank'
  ELSE coalesce(
    (SELECT o.class FROM closure_type_override o WHERE o.problemcode = pc AND o.text_norm = {NORM.format(x='t')}),
    (SELECT c.class FROM closure_text_class c WHERE c.text_norm = {NORM.format(x='t')}),
    CASE {pref} ELSE 'info_other' END)
  END;""")
lines.append(f"""CREATE OR REPLACE MACRO closure_rule(pc, t) AS CASE
  WHEN {NORM.format(x='t')} = '' THEN 'blank:no_text'
  ELSE coalesce(
    (SELECT o.rule FROM closure_type_override o WHERE o.problemcode = pc AND o.text_norm = {NORM.format(x='t')}),
    (SELECT c.rule FROM closure_text_class c WHERE c.text_norm = {NORM.format(x='t')}),
    CASE {prefr} ELSE 'info_other:unlisted (not yet reviewed)' END)
  END;""")
sql = "\n".join(lines) + "\n"
(B / "closure_class.sql").write_text(sql)

con = duckdb.connect()
con.execute(sql)
pairs = con.execute(f"SELECT DISTINCT PROBLEMCODE, PUBLICRESOLUTION FROM '{B/'private'/'csb_2024_2026.parquet'}' WHERE STATUS='CLOSED'").fetchall()
bad = 0
for pc, t in pairs:
    s = con.execute("SELECT closure_class(?, ?)", [pc, t]).fetchone()[0]
    if s != classify(pc, t)[0]:
        bad += 1
        print("MISMATCH", repr(pc), repr(t), s, classify(pc, t)[0])
print(f"SQL vs Python on {len(pairs)} (type, text) pairs: {bad} mismatches")
